self.addEventListener("install", (event) => {
	event.waitUntil(
		caches.open(CACHE_NAME)
			.then((cache) => cache.addAll(APP_SHELL.map((url) => new Request(url, { cache: "reload" }))))
			.then(() => self.skipWaiting())
	);
});

self.addEventListener("activate", (event) => {
	event.waitUntil(
		caches.keys()
			.then((cacheNames) => Promise.all(
				cacheNames
					.filter((cacheName) => cacheName.startsWith("voicer-pwa-") && cacheName !== CACHE_NAME)
					.map((cacheName) => caches.delete(cacheName))
			))
			.then(() => self.clients.claim())
	);
});

self.addEventListener("fetch", (event) => {
	const requestUrl = new URL(event.request.url);
	if (event.request.method !== "GET" || requestUrl.origin !== self.location.origin) {
		return;
	}

	event.respondWith(
		caches.match(event.request).then((cachedResponse) => {
			if (cachedResponse) {
				return cachedResponse;
			}

			if (event.request.mode === "navigate") {
				return fetch(event.request).catch(() => {
					const appPath = new URL("./app.html", self.location.href).pathname;
					const voicerPath = new URL("./voicer.html", self.location.href).pathname;
					const aboutPath = new URL("./apie.html", self.location.href).pathname;
					const fallback = requestUrl.pathname === appPath
						? "./app.html"
						: requestUrl.pathname === voicerPath ? "./voicer.html"
							: requestUrl.pathname === aboutPath ? "./apie.html" : "./index.html";
					return caches.match(fallback);
				});
			}
			if (requestUrl.pathname.includes("/assets/icons/biblioteka/") || requestUrl.pathname.includes("/assets/audio/frazes/") || decodeURIComponent(requestUrl.pathname).includes("/assets/audio/frazes/")) {
				return fetch(event.request).then((response) => {
					if (response.ok) {
						const copy = response.clone();
						caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
					}
					return response;
				});
			}
			return fetch(event.request);
		})
	);
});
